import { readFile, mkdir, writeFile, readdir, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { renderProjectDetailHTML } from '../js/rendering.js';

const escapeHTML = (value) => String(value).replace(/[&<>"']/g, (char) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
})[char]);

function replaceOnce(source, needle, replacement) {
  if (!source.includes(needle)) throw new Error(`Project template is missing: ${needle}`);
  return source.replace(needle, replacement);
}

const projects = JSON.parse(await readFile('data/projects.json', 'utf8'));
const template = await readFile('project.html', 'utf8');
const domain = (await readFile('CNAME', 'utf8')).trim();
const origin = `https://${domain}/`;
const seen = new Set();

for (const project of projects) {
  const { slug, title, summary, cover } = project;
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) || seen.has(slug)) {
    throw new Error(`Invalid or duplicate project slug: ${slug}`);
  }
  seen.add(slug);
  const url = new URL(`project/${slug}`, origin).href;
  const image = new URL(cover, origin).href;
  const name = `${title} — Maxwell Ainatchi`;
  const metadata = [
    `<link rel="canonical" href="${escapeHTML(url)}">`,
    `<meta property="og:type" content="article">`,
    `<meta property="og:site_name" content="Maxwell Ainatchi">`,
    `<meta property="og:title" content="${escapeHTML(name)}">`,
    `<meta property="og:description" content="${escapeHTML(summary)}">`,
    `<meta property="og:url" content="${escapeHTML(url)}">`,
    `<meta property="og:image" content="${escapeHTML(image)}">`,
    `<meta property="og:image:alt" content="${escapeHTML(title)} cover artwork">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${escapeHTML(name)}">`,
    `<meta name="twitter:description" content="${escapeHTML(summary)}">`,
    `<meta name="twitter:image" content="${escapeHTML(image)}">`
  ].join('');

  let html = replaceOnce(template, '<meta name="description" content="Project detail by Maxwell Ainatchi.">',
    `<base href="../../"><meta name="description" content="${escapeHTML(summary)}">${metadata}`);
  html = replaceOnce(html, '<title>Project — Maxwell Ainatchi</title>', `<title>${escapeHTML(name)}</title>`);
  html = replaceOnce(html, '<p id="page-status" class="status" role="status">Loading project…</p><article id="project-detail"></article>',
    `<article id="project-detail">${renderProjectDetailHTML(project)}</article>`);
  html = replaceOnce(html, '<script type="module" src="js/project-detail.js?v=20260927a"></script>', '');

  const dir = join('project', slug);
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, 'index.html'), `<!-- Generated from data/projects.json. Run npm run build. -->\n${html}`);
}

// Remove only pages previously generated by this script when a slug is deleted.
for (const entry of await readdir('project', { withFileTypes: true })) {
  if (!entry.isDirectory() || seen.has(entry.name)) continue;
  const path = join('project', entry.name, 'index.html');
  const old = await readFile(path, 'utf8').catch(() => '');
  if (old.startsWith('<!-- Generated from data/projects.json.')) await rm(join('project', entry.name), { recursive: true });
}
